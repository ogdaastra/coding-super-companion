import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

/** Files copied from `public/` (not part of the bundle), with their contents. */
function publicFiles(dir: string): { name: string; data: Buffer }[] {
  const out: { name: string; data: Buffer }[] = [];
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      // `_headers` is host configuration, not a resource the page requests.
      else if (e.name !== '_headers' && !e.name.startsWith('.')) out.push({ name: relative(dir, p).split(sep).join('/'), data: readFileSync(p) });
    }
  };
  try {
    walk(dir);
  } catch {
    /* no public directory */
  }
  return out;
}

/**
 * Emits `sw.js`, a service worker that precaches every file of the build so the
 * application (including the WebAssembly engine) works offline after the first
 * visit, and so it can be installed as an app. Generated at build time with the
 * exact asset list, including the files copied from `public/` (web app manifest,
 * icons). The cache version covers the bundle's hashed file names and the
 * contents of the public files, which keep their names when they change.
 */
export function serviceWorker(): Plugin {
  let publicDir = '';
  return {
    name: 'neuroform-service-worker',
    apply: 'build',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const pub = publicFiles(publicDir);
      const assets = ['./', ...files.map((f) => `./${f}`), ...pub.map((f) => `./${f.name}`)];
      const version = createHash('sha256');
      for (const f of files.slice().sort()) version.update(f).update('\0');
      for (const f of pub.sort((a, b) => a.name.localeCompare(b.name))) version.update(f.name).update('\0').update(f.data);
      const source = `// Generated by scripts/vite-sw-plugin.ts
const CACHE = 'neuroform-${version.digest('hex').slice(0, 12)}';
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('neuroform-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Navigations: network first (fresh deployments), cache when offline.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((r) => { const c = r.clone(); caches.open(CACHE).then((x) => x.put('./', c)); return r; }).catch(() => caches.match('./')));
    return;
  }
  // Hashed assets: cache first.
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((r) => {
    if (r.ok) { const c = r.clone(); caches.open(CACHE).then((x) => x.put(req, c)); }
    return r;
  })));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
