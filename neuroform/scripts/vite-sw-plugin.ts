import type { Plugin } from 'vite';

/**
 * Emits `sw.js`, a service worker that precaches every file of the build so the
 * application (including the WebAssembly engine) works offline after the first
 * visit. Generated at build time with the exact asset list and a content version,
 * so no runtime dependency or manifest file is needed.
 */
export function serviceWorker(): Plugin {
  return {
    name: 'neuroform-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const assets = ['./', ...files.map((f) => `./${f}`)];
      const version = files.slice().sort().join('|');
      let hash = 0;
      for (let i = 0; i < version.length; i++) hash = (Math.imul(31, hash) + version.charCodeAt(i)) | 0;
      const source = `// Generated by scripts/vite-sw-plugin.ts
const CACHE = 'neuroform-${(hash >>> 0).toString(36)}';
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('neuroform-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Navigations: network first (fresh deployments), cache when offline.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((r) => { const c = r.clone(); caches.open(CACHE).then((x) => x.put('./', c)); return r; }).catch(() => caches.match('./')));
    return;
  }
  // Hashed assets: cache first.
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((r) => {
    if (r.ok) { const c = r.clone(); caches.open(CACHE).then((x) => x.put(req, c)); }
    return r;
  })));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}
